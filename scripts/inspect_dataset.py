"""Dataset inspection -> docs/01_dataset_inspection.md + docs/data_dictionary.md

Every number in those documents is computed here from the actual data, so the
documentation can be regenerated at any time and never drifts from reality.

Run:  .venv/bin/python scripts/inspect_dataset.py
"""
from __future__ import annotations

import pandas as pd

from predictops.config import load_config, project_path, sensor_columns
from predictops.data.ingestion import load_intermediate

cfg = load_config()
df = load_intermediate()
analog, digital = cfg["dataset"]["analog_sensors"], cfg["dataset"]["digital_sensors"]
sensors = sensor_columns(cfg)
raw_csv = project_path(cfg["paths"]["raw_csv"])

# ---------- label construction for inspection only (in-window flag) ----------
df["in_failure_window"] = 0
df["event_id"] = 0
for ev in cfg["failure_events"]:
    m = df.timestamp.between(pd.Timestamp(ev["start"]), pd.Timestamp(ev["end"]))
    df.loc[m, "in_failure_window"] = 1
    df.loc[m, "event_id"] = ev["id"]

L: list[str] = []
w = L.append

w("# 01 — Dataset Inspection Report\n")
w("_Auto-generated by `scripts/inspect_dataset.py` from the actual data. Do not edit by hand._\n")

w("## 1. Files\n")
w("| File | Size | Role |\n|---|---|---|")
w(f"| `data/raw/{raw_csv.name}` | {raw_csv.stat().st_size/1e6:.1f} MB | All sensor readings (read-only, SHA-256 in `data/raw/SHA256SUMS`) |")
w("| `data/raw/Data Description_Metro.pdf` | 0.1 MB | Official sensor descriptions + failure report table |")
w("| `data/intermediate/metropt3.parquet` | derived | Typed, sorted, segmented copy produced by `scripts/build_intermediate.py` |\n")
w("The two raw files are related only through time: the PDF's failure windows are matched to CSV rows by timestamp. There is no shared key.\n")

w("## 2. Shape and types\n")
w(f"- Rows: **{len(df):,}**  ·  Raw columns: 17 (unnamed index, `timestamp`, 15 sensors)")
w(f"- Time span: **{df.timestamp.min()}** → **{df.timestamp.max()}**")
w(f"- In-memory size after dtype optimisation: {df[['timestamp', *sensors]].memory_usage(deep=True).sum()/1e6:.1f} MB "
  "(analog → float32, digital → int8)\n")

w("## 3. Missing values, duplicates, ordering\n")
w(f"- Missing values (all sensors): **{int(df[sensors].isna().sum().sum())}**")
w(f"- Duplicate timestamps: **{int(df.timestamp.duplicated().sum())}**")
w(f"- Fully duplicated sensor rows (same readings at different times): {int(df[sensors].duplicated().sum()):,} "
  "— expected for an idle machine with quantised sensors, **not** data errors, so they are kept.")
w("- Timestamps in the raw file are already strictly increasing.\n")

dt = df.dt_seconds.iloc[1:]
w("## 4. Sampling frequency\n")
w("The PDF states 1 Hz / 15,169,480 points. **The provided CSV is sampled every ~10 s** "
  "(raw index increments by exactly 10 per row, i.e. the file is a 1-in-10 subsample of the 1 Hz log).\n")
vc = dt.round().value_counts()
w("| Interval (s) | Count | Share |\n|---|---|---|")
for k, v in vc.head(6).items():
    w(f"| {k:.0f} | {v:,} | {v/len(dt):.2%} |")
w(f"\nMedian interval: {dt.median():.0f} s. **All window sizes in this project are therefore defined in seconds/minutes assuming ~10 s steps.**\n")

gaps = df.loc[df.dt_seconds > cfg["dataset"]["segment_gap_seconds"], ["timestamp", "dt_seconds"]]
w("## 5. Recording gaps and segments\n")
w(f"- Gaps > {cfg['dataset']['segment_gap_seconds']} s: **{len(gaps)}**, totalling **{gaps.dt_seconds.sum()/3600:.0f} h** of no data.")
w(f"- These split the data into **{df.segment_id.nunique()} continuous segments** (`segment_id`).")
w("- Interpretation: the logger is off when the train is not in service (nights / depot). They are sensor *interruptions*, not random missing values, "
  "so they are **never interpolated**; rolling features and DL sequences are computed within a segment only.\n")
w("Largest gaps:\n\n| Gap ends at | Length (h) |\n|---|---|")
for _, r in gaps.nlargest(10, "dt_seconds").iterrows():
    w(f"| {r.timestamp} | {r.dt_seconds/3600:.1f} |")
w("")

w("## 6. Sensor statistics\n")
desc = df[analog].describe(percentiles=[.01, .5, .99]).T
w("### Analog sensors\n")
w("| Sensor | mean | std | min | 1% | median | 99% | max |\n|---|---|---|---|---|---|---|---|")
for c, r in desc.iterrows():
    w(f"| {c} | {r['mean']:.3f} | {r['std']:.3f} | {r['min']:.3f} | {r['1%']:.3f} | {r['50%']:.3f} | {r['99%']:.3f} | {r['max']:.3f} |")
w("\n### Digital sensors (share of time = 1)\n")
w("| Sensor | P(=1) | Values |\n|---|---|---|")
for c in digital:
    w(f"| {c} | {df[c].mean():.3%} | {sorted(df[c].unique().tolist())} |")
w("")

w("## 7. Outliers (IQR rule, analog sensors)\n")
w("Counted, **not removed**: in this machine, extreme values are often the very behaviour we want to detect "
  "(e.g. pressure collapse during an air leak).\n")
w("| Sensor | IQR outliers | Share | Share inside failure windows |\n|---|---|---|---|")
for c in analog:
    q1, q3 = df[c].quantile([.25, .75])
    iqr = q3 - q1
    m = (df[c] < q1 - 1.5 * iqr) | (df[c] > q3 + 1.5 * iqr)
    inside = df.loc[m, "in_failure_window"].mean() if m.any() else 0
    w(f"| {c} | {int(m.sum()):,} | {m.mean():.2%} | {inside:.1%} |")
w("\nNote: distributions are multi-modal (compressor on/off/loaded), so IQR flags whole operating modes for some sensors; "
  "proper anomaly detection must be regime-aware (Phase 8).\n")

w("## 8. Constant / near-constant and redundant features\n")
w("| Sensor | Most frequent value share |\n|---|---|")
for c in sensors:
    w(f"| {c} | {df[c].value_counts(normalize=True).iloc[0]:.1%} |")
corr = df[sensors].corr()
pairs = [(a, b, corr.loc[a, b]) for i, a in enumerate(sensors) for b in sensors[i + 1:] if abs(corr.loc[a, b]) >= 0.9]
w("\nHighly correlated pairs (|r| ≥ 0.9) — candidates for redundancy:\n")
w("| A | B | r |\n|---|---|---|")
for a, b, r in sorted(pairs, key=lambda x: -abs(x[2])):
    w(f"| {a} | {b} | {r:.3f} |")
w("\nNo sensor is strictly constant. LPS and Pressure_switch are near-constant (≥99% one value) but LPS is physically meaningful "
  "(pressure < 7 bar), so it is kept and judged in feature selection.\n")

w("## 9. Failure-label investigation\n")
w("- **No label column exists.** The PDF states: \"The dataset is unlabeled\".")
w("- Ground truth = 4 air-leak windows from company reports (table in PDF, copied verbatim into `configs/config.yaml`).")
w("- **Inconsistencies in the official table (documented, not altered):** two rows are numbered \"#1\"; "
  "event 2 (29 May) lists \"Maintenance on 30Apr\", which precedes it and likely belongs to event 1.\n")
w("| Event | Window | Rows in CSV | Hours of data | Mean TP3 inside | Mean TP3 outside | LPS=1 rows |\n|---|---|---|---|---|---|---|")
outside_tp3 = df.loc[df.in_failure_window == 0, "TP3"].mean()
for ev in cfg["failure_events"]:
    sub = df[df.event_id == ev["id"]]
    w(f"| {ev['id']} | {ev['start']} → {ev['end']} | {len(sub):,} | {len(sub)*10/3600:.1f} | {sub.TP3.mean():.3f} | {outside_tp3:.3f} | {int(sub.LPS.sum())} |")
pos = int(df.in_failure_window.sum())
w(f"\n- Rows inside any failure window: **{pos:,} ({pos/len(df):.2%})** → imbalance ratio ≈ 1:{(len(df)-pos)/pos:.0f}.")
w("- Only **4 independent events** → any supervised metric rests on very few events and must be reported per event.")
silent = [ev["id"] for ev in cfg["failure_events"] if df.loc[df.event_id == ev["id"], "LPS"].sum() == 0]
w(f"- LPS (low-pressure switch) is not a usable label: it never fires during event(s) {silent}.")
w("- Mean TP3 (panel pressure) is lower inside every failure window than outside — consistent with an air leak and a first hint of a learnable signal.\n")

w("## 10. Feasibility conclusions\n")
w("| Task | Verdict | Reason |\n|---|---|---|")
w("| Unsupervised / semi-supervised anomaly detection | **Primary** | Unlabeled data; failure windows serve as an evaluation set (approach of the dataset authors) |")
w("| Supervised *failure-window detection* (is the APU currently in a reported failure window?) | Feasible | ~2% positive rows, 4 events |")
w("| Supervised *early warning* (failure window starts within H) | Feasible but weak evidence | Only 4 onsets; metrics will be high-variance |")
w("| RUL regression | **Not claimed** | 4 events, no run-to-failure degradation trajectories |")
w("| Cross-machine generalisation | **Not claimed** | Single compressor |")

out = project_path("docs/01_dataset_inspection.md")
out.write_text("\n".join(L) + "\n", encoding="utf-8")

# ------------------------------ data dictionary ------------------------------
meaning = {
    "TP2": ("analog", "bar", "Pressure on the compressor."),
    "TP3": ("analog", "bar", "Pressure generated at the pneumatic panel."),
    "H1": ("analog", "bar", "Pressure generated by the pressure drop when the cyclonic separator filter discharges."),
    "DV_pressure": ("analog", "bar", "Pressure drop when the towers discharge the air dryers; ~0 means the compressor is operating under load."),
    "Reservoirs": ("analog", "bar", "Downstream reservoir pressure; should be close to TP3."),
    "Oil_temperature": ("analog", "°C", "Oil temperature on the compressor."),
    "Motor_current": ("analog", "A", "Current of one motor phase: ~0 A off, ~4 A offloaded, ~7 A under load, ~9 A at start."),
    "COMP": ("digital", "0/1", "Air intake valve signal; active when there is no air intake (compressor off or offloaded)."),
    "DV_eletric": ("digital", "0/1", "Compressor outlet valve signal; active when under load. (Spelling as in the dataset.)"),
    "Towers": ("digital", "0/1", "Which air-drying tower is active: 0 = tower one, 1 = tower two."),
    "MPG": ("digital", "0/1", "Starts the compressor under load when APU pressure < 8.2 bar; drives COMP."),
    "LPS": ("digital", "0/1", "Low-pressure switch: activates when pressure drops below 7 bar."),
    "Pressure_switch": ("digital", "0/1", "Detects discharge in the air-drying towers."),
    "Oil_level": ("digital", "0/1", "Active when oil is below expected level."),
    "Caudal_impulses": ("digital", "0/1", "Pulse output counting air flow from the APU to the reservoirs."),
}
D = ["# Data Dictionary — MetroPT-3\n",
     "_Meanings from the official `Data Description_Metro.pdf`; ranges computed from the data by `scripts/inspect_dataset.py`._\n",
     "| Column | Type | Unit | Stored dtype | Observed range | Meaning |", "|---|---|---|---|---|---|",
     "| `Unnamed: 0` → `raw_index` | index | – | int64 | 0 … 15,169,470 (step 10) | Row number in the original 1 Hz log; used only for traceability, never as a feature |",
     f"| `timestamp` | datetime | – | datetime64 | {df.timestamp.min()} … {df.timestamp.max()} | Time of the reading (~10 s steps) |"]
for c in sensors:
    kind, unit, txt = meaning[c]
    D.append(f"| `{c}` | {kind} | {unit} | {'float32' if kind=='analog' else 'int8'} | {df[c].min():.3f} … {df[c].max():.3f} | {txt} |")
D += ["\n## Derived columns (added by PredictOps, not in raw data)\n",
      "| Column | Meaning |", "|---|---|",
      "| `dt_seconds` | Seconds since previous reading |",
      f"| `segment_id` | Continuous recording segment; increments after a gap > {cfg['dataset']['segment_gap_seconds']} s |"]
project_path("docs/data_dictionary.md").write_text("\n".join(D) + "\n", encoding="utf-8")
print("wrote docs/01_dataset_inspection.md and docs/data_dictionary.md")
